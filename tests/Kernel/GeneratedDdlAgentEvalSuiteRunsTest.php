        'CREATE INDEX "EntityAgentEvalSuiteCases_idx_aiConversationId" ON "EntityAgentEvalSuiteCases" ("aiConversationId")',
        'CREATE INDEX "EntityAgentEvalSuiteCases_idx_verdict" ON "EntityAgentEvalSuiteCases" ("verdict")',
        'ALTER TABLE "EntityAgentEvalSuiteCases" ADD CONSTRAINT "EntityAgentEvalSuiteCases_fk_agentEvalSuiteRunId" FOREIGN KEY ("agentEvalSuiteRunId") '
        . 'REFERENCES "EntityAgentEvalSuiteRuns" ("id") ON UPDATE CASCADE ON DELETE CASCADE',
    ];

    protected ?string $tablePrefixBefore = null;

    protected function setUp(): void
    {
        parent::setUp();
        $this->tablePrefixBefore = $_ENV['DATABASE_TABLE_PREFIX'] ?? null;
        $_ENV['DATABASE_TABLE_PREFIX'] = self::APPLICATION_TABLE_PREFIX;
    }

    protected function tearDown(): void
    {
        if ($this->tablePrefixBefore === null) {
            unset($_ENV['DATABASE_TABLE_PREFIX']);
        } else {
            $_ENV['DATABASE_TABLE_PREFIX'] = $this->tablePrefixBefore;
        }
        parent::tearDown();
    }

    public function testTheRunTableOnMariaDb(): void
    {
        $generatedSql = $this->buildDatabaseModel(AgentEvalSuiteRun::class)->getSql();
        self::assertSame(
            "CREATE TABLE IF NOT EXISTS `EntityAgentEvalSuiteRuns`(\n\t" . implode(",\n\t", self::RUN_COLUMNS_MARIADB) . ",\n\tPRIMARY KEY (`id`))",
            $this->findCreateTableStatement($generatedSql)
        );
        self::assertSame(
            [
                'CREATE INDEX IF NOT EXISTS `idx_suiteLabel` ON `EntityAgentEvalSuiteRuns` (`suiteLabel`)',
                'CREATE INDEX IF NOT EXISTS `idx_command` ON `EntityAgentEvalSuiteRuns` (`command`)',
                'CREATE INDEX IF NOT EXISTS `idx_startedAt` ON `EntityAgentEvalSuiteRuns` (`startedAt`)',
                'CREATE INDEX IF NOT EXISTS `idx_created` ON `EntityAgentEvalSuiteRuns` (`created`)',
                'CREATE INDEX IF NOT EXISTS `idx_updated` ON `EntityAgentEvalSuiteRuns` (`updated`)',
            ],
            $this->findStatementsStartingWith($generatedSql, 'CREATE INDEX')
        );
        self::assertSame([], $this->findStatementsStartingWith($generatedSql, 'ALTER TABLE `EntityAgentEvalSuiteRuns` ADD CONSTRAINT'));
    }

    public function testTheCaseTableOnMariaDb(): void
    {
        $generatedSql = $this->buildDatabaseModel(AgentEvalSuiteCase::class)->getSql();
        self::assertSame(
            "CREATE TABLE IF NOT EXISTS `EntityAgentEvalSuiteCases`(\n\t" . implode(",\n\t", self::CASE_COLUMNS_MARIADB) . ",\n\tPRIMARY KEY (`id`))",
            $this->findCreateTableStatement($generatedSql)
        );
        self::assertSame(
            [
                'CREATE INDEX IF NOT EXISTS `idx_agentEvalSuiteRunId` ON `EntityAgentEvalSuiteCases` (`agentEvalSuiteRunId`)',
                'CREATE INDEX IF NOT EXISTS `idx_caseId` ON `EntityAgentEvalSuiteCases` (`caseId`)',
                'CREATE INDEX IF NOT EXISTS `idx_aiConversationId` ON `EntityAgentEvalSuiteCases` (`aiConversationId`)',
                'CREATE INDEX IF NOT EXISTS `idx_verdict` ON `EntityAgentEvalSuiteCases` (`verdict`)',
            ],
            $this->findStatementsStartingWith($generatedSql, 'CREATE INDEX')
        );
        self::assertSame(
            [
                'ALTER TABLE `EntityAgentEvalSuiteCases` ADD CONSTRAINT `fk_EntityAgentEvalSuiteCases_agentEvalSuiteRunId` FOREIGN KEY IF NOT EXISTS '
                . '(`agentEvalSuiteRunId`) REFERENCES `EntityAgentEvalSuiteRuns` (`id`) ON UPDATE CASCADE ON DELETE CASCADE',
            ],
            $this->findStatementsStartingWith($generatedSql, 'ALTER TABLE `EntityAgentEvalSuiteCases` ADD CONSTRAINT')
        );
    }

    public function testBothTablesOnPostgres(): void
    {
        $ddlRenderer = DialectResolver::forDriver('pdo_pgsql')->ddlRenderer();
        $statements = [];
        foreach ([AgentEvalSuiteRun::class, AgentEvalSuiteCase::class] as $entityClass) {
            foreach ($ddlRenderer->renderCreate($this->buildDatabaseModel($entityClass))->getSqlList() as $sql) {
                $statements[] = $sql;
            }
        }
        self::assertSame(self::STATEMENTS_POSTGRES, $statements);
    }

    public function testTheShippedModelsCarryNoPrefix(): void
    {
        $_ENV['DATABASE_TABLE_PREFIX'] = '';
        self::assertSame('AgentEvalSuiteRuns', $this->buildDatabaseModel(AgentEvalSuiteRun::class)->sqlTableName);
        self::assertSame('AgentEvalSuiteCases', $this->buildDatabaseModel(AgentEvalSuiteCase::class)->sqlTableName);
    }

    /** The model of the entity under the current table prefix (built anew: the generator's own list is cached). */
    protected function buildDatabaseModel(string $entityClass): DatabaseModel
    {
        $databaseModel = DatabaseModel::fromEntityClass($entityClass);
        self::assertInstanceOf(DatabaseModel::class, $databaseModel, $entityClass);
        return $databaseModel;
    }

    /** The CREATE TABLE statement without its engine and collation lines. */
    protected function findCreateTableStatement(string $generatedSql): string
    {
        self::assertSame(1, preg_match('/CREATE TABLE IF NOT EXISTS .*?PRIMARY KEY \(`id`\)\)/s', $generatedSql, $matches));
        return $matches[0];
    }

    /**
     * @return string[] The statements of the generated SQL that start with `$prefix`, without their `;`
     */
    protected function findStatementsStartingWith(string $generatedSql, string $prefix): array
    {
        $statements = [];
        foreach (explode("\n", $generatedSql) as $line) {
            if (str_starts_with(trim($line), $prefix)) {
                $statements[] = rtrim(trim($line), ';');
            }
        }
        return $statements;
    }
}
