        . '    "updated" timestamp(0) without time zone,' . "\n"
        . '    PRIMARY KEY ("id")' . "\n"
        . ')',
        'CREATE INDEX "EntityAgentEvalSuiteRuns_idx_suiteLabel" ON "EntityAgentEvalSuiteRuns" ("suiteLabel")',
        'CREATE INDEX "EntityAgentEvalSuiteRuns_idx_command" ON "EntityAgentEvalSuiteRuns" ("command")',
        'CREATE INDEX "EntityAgentEvalSuiteRuns_idx_startedAt" ON "EntityAgentEvalSuiteRuns" ("startedAt")',
        'CREATE INDEX "EntityAgentEvalSuiteRuns_idx_created" ON "EntityAgentEvalSuiteRuns" ("created")',
        'CREATE INDEX "EntityAgentEvalSuiteRuns_idx_updated" ON "EntityAgentEvalSuiteRuns" ("updated")',
        'CREATE TABLE "EntityAgentEvalSuiteCases" (' . "\n"
        . '    "agentEvalSuiteRunId" bigint NOT NULL,' . "\n"
        . '    "caseId" varchar(191) COLLATE "ddd_ci_ai" NOT NULL,' . "\n"
        . '    "suiteName" varchar(32) COLLATE "ddd_ci_ai",' . "\n"
        . '    "fixtureName" varchar(128) COLLATE "ddd_ci_ai",' . "\n"
        . '    "modelName" varchar(64) COLLATE "ddd_ci_ai",' . "\n"
        . '    "flavor" varchar(16) COLLATE "ddd_ci_ai",' . "\n"
        . '    "aiConversationId" integer,' . "\n"
        . '    "verdict" varchar(16) COLLATE "ddd_ci_ai" NOT NULL,' . "\n"
        . '    "findings" text COLLATE "ddd_ci_ai",' . "\n"
