use DDD\Tests\Agents\Support\UnitTestCase;

/**
 * The tables of the stored evaluation runs, column by column, as the generator renders them for MariaDB and for
 * PostgreSQL. The expected statements are those of an application with the table prefix `Entity` (the tables
 * `EntityAgentEvalSuiteRuns` and `EntityAgentEvalSuiteCases`): the stored format of every column, type, nullability,
 * default, index and foreign key such an application's tables have.
 * Generated in memory under the package kernel, nothing is written and no database is asked.
 */
class GeneratedDdlAgentEvalSuiteRunsTest extends UnitTestCase
{
    /** @var string The table prefix of the application whose tables the expected statements describe */
    protected const string APPLICATION_TABLE_PREFIX = 'Entity';

    /** @var string[] The column definitions of the run table on MariaDB, in their order */
    protected const array RUN_COLUMNS_MARIADB = [
        '`suiteLabel` VARCHAR(128) DEFAULT NULL',
        '`command` VARCHAR(64) NOT NULL',
        '`host` VARCHAR(128) DEFAULT NULL',
        '`startedAt` DATETIME NOT NULL',
        '`finishedAt` DATETIME DEFAULT NULL',
        '`casesTotal` INT DEFAULT 0',
        '`casesPassed` INT DEFAULT 0',
        '`casesFailed` INT DEFAULT 0',
        '`casesErrored` INT DEFAULT 0',
        '`casesNotApplicable` INT DEFAULT 0',
        '`casesFailedAsExpected` INT DEFAULT 0',
        '`runOptionsJson` TEXT DEFAULT NULL',
        '`logDirectoryName` VARCHAR(191) DEFAULT NULL',
        '`id` INT UNSIGNED NOT NULL AUTO_INCREMENT',
        '`created` DATETIME DEFAULT NULL',
        '`updated` DATETIME DEFAULT NULL',
    ];

    /** @var string[] The column definitions of the case table on MariaDB, in their order */
    protected const array CASE_COLUMNS_MARIADB = [
        '`agentEvalSuiteRunId` INT UNSIGNED NOT NULL',
        '`caseId` VARCHAR(191) NOT NULL',
        '`suiteName` VARCHAR(32) DEFAULT NULL',
        '`fixtureName` VARCHAR(128) DEFAULT NULL',
        '`modelName` VARCHAR(64) DEFAULT NULL',
        '`flavor` VARCHAR(16) DEFAULT NULL',
        '`aiConversationId` INT DEFAULT NULL',
        '`verdict` VARCHAR(16) NOT NULL',
        '`findings` TEXT DEFAULT NULL',
        '`wallSeconds` DOUBLE DEFAULT NULL',
        '`agentSeconds` DOUBLE DEFAULT NULL',
        '`ownerTurns` INT DEFAULT NULL',
        '`modelCalls` INT DEFAULT NULL',
        '`toolCalls` INT DEFAULT NULL',
        '`costUsd` DOUBLE DEFAULT NULL',
        '`id` INT UNSIGNED NOT NULL AUTO_INCREMENT',
    ];

    /** @var string[] The statements of both tables on PostgreSQL, in their order */
    protected const array STATEMENTS_POSTGRES = [
        'CREATE TABLE "EntityAgentEvalSuiteRuns" (' . "\n"
        . '    "suiteLabel" varchar(128) COLLATE "ddd_ci_ai",' . "\n"
        . '    "command" varchar(64) COLLATE "ddd_ci_ai" NOT NULL,' . "\n"
        . '    "host" varchar(128) COLLATE "ddd_ci_ai",' . "\n"
        . '    "startedAt" timestamp(0) without time zone NOT NULL,' . "\n"
        . '    "finishedAt" timestamp(0) without time zone,' . "\n"
        . '    "casesTotal" integer DEFAULT 0,' . "\n"
        . '    "casesPassed" integer DEFAULT 0,' . "\n"
        . '    "casesFailed" integer DEFAULT 0,' . "\n"
        . '    "casesErrored" integer DEFAULT 0,' . "\n"
        . '    "casesNotApplicable" integer DEFAULT 0,' . "\n"
        . '    "casesFailedAsExpected" integer DEFAULT 0,' . "\n"
        . '    "runOptionsJson" text COLLATE "ddd_ci_ai",' . "\n"
        . '    "logDirectoryName" varchar(191) COLLATE "ddd_ci_ai",' . "\n"
        . '    "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,' . "\n"
